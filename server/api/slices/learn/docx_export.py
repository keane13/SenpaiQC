"""8D report as a Word document. Opens in Google Docs (upload to Drive) or Microsoft Word."""
from __future__ import annotations

import io
from datetime import datetime, timezone

from docx import Document
from docx.shared import Pt, RGBColor

from domain.models import EIGHT_D_KEYS

TITLES = {
    "D1_team": "D1 · Team",
    "D2_problem": "D2 · Problem description",
    "D3_containment": "D3 · Interim containment",
    "D4_root_cause": "D4 · Root cause",
    "D5_corrective_actions": "D5 · Permanent corrective actions",
    "D6_implementation": "D6 · Implementation and validation",
    "D7_prevention": "D7 · Prevent recurrence",
    "D8_recognition": "D8 · Closure and recognition",
}


def report_docx(report: dict, inv: dict | None) -> bytes:
    doc = Document()
    doc.styles["Normal"].font.name = "Calibri"
    doc.styles["Normal"].font.size = Pt(11)

    subject = f"{inv['defect_name']} on {inv.get('part_number', '')}" if inv else report["id"]
    doc.add_heading(f"8D Report — {subject}", level=0)

    meta = doc.add_table(rows=0, cols=2)
    meta.style = "Light List Accent 1"
    rows = [
        ("Report", report["id"]),
        ("Status", report.get("status", "draft").upper()),
        ("Drafted by", report.get("generated_by", "")),
        ("Edited by", report.get("edited_by") or "—"),
        ("Last updated", (report.get("updated_at") or report.get("created_at") or "")[:16].replace("T", " ")),
    ]
    if inv:
        rows += [
            ("Investigation", inv["id"]),
            ("Flagged subgroup", inv["shift_key"]),
            ("Defect rate at flag", f"{inv['rate']:.1%} (control limit {inv['ucl']:.1%}, normal {inv['center']:.1%})"),
        ]
    for k, v in rows:
        cells = meta.add_row().cells
        cells[0].text, cells[1].text = k, str(v)

    if inv and inv.get("hypotheses"):
        doc.add_heading("Ranked root-cause hypotheses (evidence from inspection records)", level=2)
        for h in inv["hypotheses"]:
            p = doc.add_paragraph(style="List Number")
            p.add_run(f"{h['statement']} ").bold = True
            p.add_run(f"({h['confidence']} confidence). Blames: " + ", ".join(f"{k} = {v}" for k, v in h["blamed"].items()))
            for e in h.get("evidence", []):
                doc.add_paragraph(e, style="List Bullet 2")

    for key in EIGHT_D_KEYS:
        doc.add_heading(TITLES.get(key, key), level=1)
        text = (report.get("sections") or {}).get(key, "").strip()
        para = doc.add_paragraph(text or "(to be completed)")
        if not text:
            para.runs[0].italic = True

    note = doc.add_paragraph()
    run = note.add_run(
        f"Generated by SenpaiQC on {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC. Sections were drafted with AI "
        "assistance from inspection records and must be reviewed by the responsible QC engineer. "
        + ("Process data in this demo is synthetic." if inv else "")
    )
    run.italic = True
    run.font.size = Pt(9)
    run.font.color.rgb = RGBColor(0x66, 0x66, 0x66)

    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()
